// gen-names emits the name-rule tables into Go and Rust from one specification.
//
// WHY. Apps are Go, the badge host is Rust, and no library spans them — so the
// rules were written twice and `VECTORS.tsv` existed to DETECT the drift. This
// removes the drift instead: both implementations are generated from
// `dlc-platform/names/RULES.json` and `WORLDS.tsv`, so they cannot disagree about
// a character class, a limit, or a reserved name.
//
// The vectors are still worth having, and they now check something different:
// that the generated code means what the rules INTENDED. Codegen makes the two
// implementations identical; it cannot make them correct.
//
// WHAT IS NOT GENERATED: the prose, the API, and the set-level logic. Every rule
// has a reason, and the reasons live beside the API in the hand-written files. A
// generator that emitted explanations too would flatten the part that makes the
// profile learnable — so this emits tables and predicates, nothing else.
//
//	go run ./cmd/gen-names            # write the generated files
//	go run ./cmd/gen-names -check     # fail if they are stale (CI)
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type limits struct {
	Component int `json:"component"`
	Path      int `json:"path"`
}

type charClass struct {
	Ranges      [][]string `json:"ranges"`
	Extra       string     `json:"extra"`
	Replacement string     `json:"replacement"`
	StemLength  int        `json:"stem_length"`
}

type badEdge struct {
	First string `json:"first"`
	Last  string `json:"last"`
}

type rules struct {
	Limits          map[string]limits `json:"limits"`
	PortableChars   charClass         `json:"portable_chars"`
	ShortNameChars  charClass         `json:"short_name_chars"`
	BadEdge         badEdge           `json:"bad_edge"`
	ReservedDevices []string          `json:"reserved_devices"`
}

// world is one row of WORLDS.tsv.
type world struct {
	ID      string
	Profile string
	// Notes is the registry's third column — carried so the generated proto can
	// say what a world IS, rather than listing six bare identifiers.
	Notes string
}

const banner = "Code generated by cmd/gen-names from dlc-platform/names/. DO NOT EDIT."

func main() {
	check := flag.Bool("check", false, "fail if the generated files are stale")
	flag.Parse()

	root := findRoot()
	spec := loadRules(filepath.Join(root, "dlc-platform/names/RULES.json"))
	worlds := loadWorlds(filepath.Join(root, "dlc-platform/names/WORLDS.tsv"))

	outputs := map[string][]byte{
		filepath.Join(root, "dlc-platform/names_gen.go"):              renderGo(spec, worlds),
		filepath.Join(root, "dlc-platform/embedded/src/names_gen.rs"): renderRust(spec, worlds),
		// THE PROTO ENUM IS GENERATED TOO, from the same rows.
		//
		// It was hand-written beside this file and drifted the first time anyone
		// used it: adding the Badger needed an edit HERE, an edit in the .proto,
		// and an edit in the test that checks they agree — three places to add
		// one world, which is how the enum came to have no name for `browser` in
		// its first draft.
		filepath.Join(root, "dlc-platform/proto/devalbo/ilc/v1/world_name.proto"): renderProto(worlds),
	}

	stale := []string{}
	for path, want := range outputs {
		got, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(got, want) {
			stale = append(stale, path)
			if !*check {
				if err := os.WriteFile(path, want, 0o644); err != nil {
					fatal("writing %s: %v", path, err)
				}
				fmt.Printf("  wrote %s\n", mustRel(root, path))
			}
		}
	}

	if *check {
		// THE GUARD THAT MAKES CODEGEN WORTH ANYTHING. Without it, someone edits a
		// generated file by hand, the two implementations diverge again, and the
		// single source has quietly become a third copy.
		if len(stale) > 0 {
			sort.Strings(stale)
			for _, path := range stale {
				fmt.Fprintf(os.Stderr, "  x stale: %s\n", mustRel(root, path))
			}
			fatal("generated files are out of date — run `make gen-names`")
		}
		fmt.Println("  generated name rules are up to date")
		return
	}
	if len(stale) == 0 {
		fmt.Println("  generated name rules already up to date")
	}
}

