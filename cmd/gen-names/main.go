func renderGo(spec rules, worlds []world) []byte {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	p("// %s", banner)
	p("//")
	p("// The RULES are here; the REASONS are in names.go, beside the API that uses")
	p("// them. Editing this file is a mistake the -check mode will catch.")
	p("")
	p("package platform")
	p("")

	portable := spec.Limits["portable"]
	p("// NameComponentMax is the portable profile's longest single component.")
	p("const NameComponentMax = %d", portable.Component)
	p("")
	p("// NamePathMax is the portable profile's longest whole path.")
	p("const NamePathMax = %d", portable.Path)
	p("")
	p("// ShortStemLength is how many characters a FAT 8.3 short name keeps.")
	p("const ShortStemLength = %d", spec.ShortNameChars.StemLength)
	p("")

	p("// portableNameChar reports whether a byte may appear in a portable name.")
	p("func portableNameChar(c byte) bool {")
	p("\treturn %s", goCharExpr(spec.PortableChars))
	p("}")
	p("")

	p("// shortNameChar maps a byte to what a FAT 8.3 field may hold.")
	p("func shortNameChar(c byte) byte {")
	p("\tif c >= 'a' && c <= 'z' {")
	p("\t\tc = c - 'a' + 'A'")
	p("\t}")
	p("\tif %s {", goCharExpr(spec.ShortNameChars))
	p("\t\treturn c")
	p("\t}")
	p("\treturn %s", quoteByteGo(spec.ShortNameChars.Replacement))
	p("}")
	p("")

	p("// badEdgeFirst reports a byte that may not START a component.")
	p("func badEdgeFirst(c byte) bool {")
	p("\treturn %s", goByteSet("c", spec.BadEdge.First))
	p("}")
	p("")
	p("// badEdgeLast reports a byte that may not END a component.")
	p("func badEdgeLast(c byte) bool {")
	p("\treturn %s", goByteSet("c", spec.BadEdge.Last))
	p("}")
	p("")

	p("// reservedDevices are names Windows refuses, with or without an extension.")
	p("var reservedDevices = [...]string{")
	for _, device := range spec.ReservedDevices {
		p("\t%q,", device)
	}
	p("}")
	p("")

	p("// profileComponentMax is the per-profile component limit.")
	p("func profileComponentMax(p NameProfile) int {")
	p("\tswitch p {")
	for _, name := range sortedKeys(spec.Limits) {
		p("\tcase %q:", name)
		p("\t\treturn %d", spec.Limits[name].Component)
	}
	p("\t}")
	p("\treturn %d", portable.Component)
	p("}")
	p("")

	p("// profilePathMax is the per-profile path limit.")
	p("func profilePathMax(p NameProfile) int {")
	p("\tswitch p {")
	for _, name := range sortedKeys(spec.Limits) {
		p("\tcase %q:", name)
		p("\t\treturn %d", spec.Limits[name].Path)
	}
	p("\t}")
	p("\treturn %d", portable.Path)
	p("}")
	p("")

	p("// knownWorlds is the registry, minus the two non-worlds.")
	p("var knownWorlds = [...]World{")
	for _, w := range worlds {
		p("\t%q,", w.ID)
	}
	p("}")
	p("")

	p("// worldNameProfile maps a world onto its rule set. Both non-worlds and")
	p("// anything unrecognised FAIL CLOSED onto the strictest profile.")
	p("func worldNameProfile(w World) NameProfile {")
	p("\tswitch w {")
	for _, w := range worlds {
		p("\tcase %q:", w.ID)
		p("\t\treturn %q", w.Profile)
	}
	p("\t}")
	p("\treturn ProfilePortable")
	p("}")

	return []byte(b.String())
}

func goCharExpr(class charClass) string {
	parts := []string{}
	for _, r := range class.Ranges {
		parts = append(parts, fmt.Sprintf("(c >= %s && c <= %s)", quoteByteGo(r[0]), quoteByteGo(r[1])))
	}
	for _, c := range []byte(class.Extra) {
		parts = append(parts, fmt.Sprintf("c == %s", quoteByteGo(string(c))))
	}
	return strings.Join(parts, " ||\n\t\t")
}

func goByteSet(v, set string) string {
	parts := []string{}
	for _, c := range []byte(set) {
		parts = append(parts, fmt.Sprintf("%s == %s", v, quoteByteGo(string(c))))
	}
	return strings.Join(parts, " || ")
}

func quoteByteGo(s string) string {
	if s == "'" {
		return `'\''`
	}
	if s == `\` {
		return `'\\'`
	}
	return "'" + s + "'"
}

