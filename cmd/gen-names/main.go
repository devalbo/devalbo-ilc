// renderProto emits the WorldName enum from the registry.
//
// The proto spelling of a world id is the id in SCREAMING_SNAKE with the enum's
// prefix: `badge-normal` becomes `WORLD_NAME_BADGE_NORMAL`. `undefined` is the
// zero value and is spelled `UNSPECIFIED` there, because proto's linter requires
// that and the registry was written with the other word — the same fact, two
// vocabularies, reconciled here rather than in anybody's head.
func renderProto(worlds []world) []byte {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	p("// %s", banner)
	p("")
	p("syntax = \"proto3\";")
	p("")
	p("package devalbo.ilc.v1;")
	p("")
	p("option go_package = \"github.com/devalbo/devalbo-ilc/dlc-platform/gen/go/devalbo/ilc/v1;ilcv1\";")
	p("")
	p("// Which host slot an app is running in.")
	p("//")
	p("// GENERATED FROM dlc-platform/names/WORLDS.tsv, which is the registry Go and")
	p("// Rust are also generated from. A world added there appears here, in the")
	p("// same commit, without anybody remembering to.")
	p("//")
	p("// `WorldName` rather than `World`, because a `WorldManifest` describes a")
	p("// world and an enum called `World` inside it reads as though it IS one. The")
	p("// values are literally names: this file is a table of them.")
	p("enum WorldName {")
	// THE TWO NON-WORLDS FIRST, and they are different in a way that matters.
	// The registry documents both at length; they are not rows in `worlds`
	// because they are the absence of one.
	p("  // Nobody declared one. The DEFAULT and the common case: an app that runs")
	p("  // everywhere has no reason to name a world.")
	p("  //")
	p("  // Spelled UNSPECIFIED here and `undefined` in the registry, because")
	p("  // proto's linter requires the former. Same fact, two words.")
	p("  WORLD_NAME_UNSPECIFIED = 0;")
	p("  // Declared, and this build does not recognise it. Distinct from")
	p("  // UNSPECIFIED: something was said and could not be understood, which the")
	p("  // badge's payload region makes routine — payloads outlive the firmware.")
	p("  WORLD_NAME_UNKNOWN = 1;")
	for i, w := range worlds {
		name := strings.ToUpper(strings.ReplaceAll(w.ID, "-", "_"))
		if w.Notes != "" {
			p("  // %s", w.Notes)
		}
		p("  WORLD_NAME_%s = %d;", name, i+2)
	}
	p("}")
	return []byte(b.String())
}

func renderRust(spec rules, worlds []world) []byte {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	p("// %s", banner)
	p("//")
	p("// The RULES are here; the REASONS are in names.rs, beside the API that uses")
	p("// them. Editing this file is a mistake the -check mode will catch.")
	p("")
	p("#![allow(dead_code)]")
	p("")

	portable := spec.Limits["portable"]
	p("/// The portable profile's longest single component.")
	p("pub const COMPONENT_MAX: usize = %d;", portable.Component)
	p("")
	p("/// The portable profile's longest whole path.")
	p("pub const PATH_MAX: usize = %d;", portable.Path)
	p("")
	p("/// How many characters a FAT 8.3 short name keeps.")
	p("pub const SHORT_STEM_LEN: usize = %d;", spec.ShortNameChars.StemLength)
	p("")

	p("/// Whether a byte may appear in a portable name.")
	p("pub const fn portable_name_char(c: u8) -> bool {")
	p("    matches!(c, %s)", rustPattern(spec.PortableChars))
	p("}")
	p("")

	p("/// Map a byte to what a FAT 8.3 field may hold.")
	p("pub const fn short_name_char(c: u8) -> u8 {")
	p("    let c = c.to_ascii_uppercase();")
	p("    if matches!(c, %s) {", rustPattern(spec.ShortNameChars))
	p("        c")
	p("    } else {")
	p("        %s", quoteByteRust(spec.ShortNameChars.Replacement))
	p("    }")
	p("}")
	p("")

	p("/// A byte that may not START a component.")
	p("pub const fn bad_edge_first(c: u8) -> bool {")
	p("    matches!(c, %s)", rustByteSet(spec.BadEdge.First))
	p("}")
	p("")
	p("/// A byte that may not END a component.")
	p("pub const fn bad_edge_last(c: u8) -> bool {")
	p("    matches!(c, %s)", rustByteSet(spec.BadEdge.Last))
	p("}")
	p("")

	p("/// Names Windows refuses, with or without an extension.")
	p("pub const RESERVED_DEVICES: [&str; %d] = [", len(spec.ReservedDevices))
	for _, device := range spec.ReservedDevices {
		p("    %q,", device)
	}
	p("];")
	p("")

	p("/// Per-profile component limit.")
	p("pub const fn profile_component_max(profile: &str) -> usize {")
	for _, name := range sortedKeys(spec.Limits) {
		p("    if str_eq(profile, %q) {", name)
		p("        return %d;", spec.Limits[name].Component)
		p("    }")
	}
	p("    COMPONENT_MAX")
	p("}")
	p("")

	p("/// Per-profile path limit.")
	p("pub const fn profile_path_max(profile: &str) -> usize {")
	for _, name := range sortedKeys(spec.Limits) {
		p("    if str_eq(profile, %q) {", name)
		p("        return %d;", spec.Limits[name].Path)
		p("    }")
	}
	p("    PATH_MAX")
	p("}")
	p("")

	// THE WIRE NUMBERS TOO, matching world_name.proto exactly.
	//
	// The badge hand-declared these beside its other proto constants, which made
	// the registry's numbering something a person had to copy correctly — and the
	// numbering is not arbitrary: it is this file's row order plus the two
	// non-worlds. Emitting both from the same loop is what makes them agree.
	p("/// `WorldName` in world_name.proto. Generated from the same rows, so the")
	p("/// badge cannot report a number the schema does not name.")
	p("pub const WORLD_NAME_UNSPECIFIED: u32 = 0;")
	p("pub const WORLD_NAME_UNKNOWN: u32 = 1;")
	for i, w := range worlds {
		p("pub const WORLD_NAME_%s: u32 = %d;", strings.ToUpper(strings.ReplaceAll(w.ID, "-", "_")), i+2)
	}
	p("")

	p("/// The registry, minus the two non-worlds.")
	p("pub const KNOWN_WORLDS: [&str; %d] = [", len(worlds))
	for _, w := range worlds {
		p("    %q,", w.ID)
	}
	p("];")
	p("")

	p("/// A world's rule set. Both non-worlds and anything unrecognised FAIL CLOSED")
	p("/// onto the strictest profile.")
	p("pub const fn world_name_profile(world: &str) -> &'static str {")
	for _, w := range worlds {
		p("    if str_eq(world, %q) {", w.ID)
		p("        return %q;", w.Profile)
		p("    }")
	}
	p("    \"portable\"")
	p("}")
	p("")

	p("/// `str` comparison usable in a `const fn`, which `==` is not.")
	p("const fn str_eq(a: &str, b: &str) -> bool {")
	p("    let (a, b) = (a.as_bytes(), b.as_bytes());")
	p("    if a.len() != b.len() {")
	p("        return false;")
	p("    }")
	p("    let mut i = 0;")
	p("    while i < a.len() {")
	p("        if a[i] != b[i] {")
	p("            return false;")
	p("        }")
	p("        i += 1;")
	p("    }")
	p("    true")
	p("}")

	return []byte(b.String())
}

func rustPattern(class charClass) string {
	parts := []string{}
	for _, r := range class.Ranges {
		parts = append(parts, fmt.Sprintf("%s..=%s", quoteByteRust(r[0]), quoteByteRust(r[1])))
	}
	for _, c := range []byte(class.Extra) {
		parts = append(parts, quoteByteRust(string(c)))
	}
	return strings.Join(parts, " | ")
}

func rustByteSet(set string) string {
	parts := []string{}
	for _, c := range []byte(set) {
		parts = append(parts, quoteByteRust(string(c)))
	}
	return strings.Join(parts, " | ")
}

func quoteByteRust(s string) string {
	switch s {
	case "'":
		return `b'\''`
	case `\`:
		return `b'\\'`
	}
	return "b'" + s + "'"
}

