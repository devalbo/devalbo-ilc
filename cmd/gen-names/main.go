func loadRules(path string) rules {
	raw, err := os.ReadFile(path)
	if err != nil {
		fatal("reading %s: %v", path, err)
	}
	var spec rules
	if err := json.Unmarshal(raw, &spec); err != nil {
		fatal("parsing %s: %v", path, err)
	}
	if len(spec.ReservedDevices) == 0 || spec.ShortNameChars.StemLength == 0 {
		fatal("%s is missing required fields", path)
	}
	return spec
}

// loadWorlds reads WORLDS.tsv, skipping the two NON-worlds: `undefined` and
// `unknown` are not registry entries, they are what a lookup RETURNS, and
// emitting them as known worlds would make `IsRealWorld` true for both.
func loadWorlds(path string) []world {
	file, err := os.Open(path)
	if err != nil {
		fatal("reading %s: %v", path, err)
	}
	defer file.Close()

	out := []world{}
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := scanner.Text()
		if strings.HasPrefix(line, "#") || !strings.Contains(line, "\t") {
			continue
		}
		id, rest, _ := strings.Cut(line, "\t")
		profile, notes, _ := strings.Cut(rest, "\t")
		if id == "undefined" || id == "unknown" {
			continue
		}
		out = append(out, world{
			ID:      id,
			Profile: strings.TrimSpace(profile),
			Notes:   strings.TrimSpace(notes),
		})
	}
	if err := scanner.Err(); err != nil {
		fatal("scanning %s: %v", path, err)
	}
	if len(out) == 0 {
		fatal("%s named no worlds", path)
	}
	return out
}

func findRoot() string {
	dir, err := os.Getwd()
	if err != nil {
		fatal("%v", err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "dlc-platform/names/RULES.json")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			fatal("could not find the repo root (no dlc-platform/names/RULES.json above %s)", dir)
		}
		dir = parent
	}
}

func mustRel(root, path string) string {
	rel, err := filepath.Rel(root, path)
	if err != nil {
		return path
	}
	return rel
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}

// sortedKeys keeps generated output DETERMINISTIC. Go map iteration is
// randomised, so without this the generator would emit a different byte sequence
// each run and `-check` would fail at random — which reads as "someone edited a
// generated file" and is the worst possible false alarm for this tool.
func sortedKeys(m map[string]limits) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
